
import os
import shutil
import numpy as np

def clean_and_create_dir(directory):
    if os.path.exists(directory):
        # Remove all files in the directory
        for filename in os.listdir(directory):
            file_path = os.path.join(directory, filename)
            try:
                if os.path.isfile(file_path) or os.path.islink(file_path):
                    os.unlink(file_path)
                elif os.path.isdir(file_path):
                    shutil.rmtree(file_path)
            except Exception as e:
                print(f'Failed to delete {file_path}. Reason: {e}')
    else:
        os.makedirs(directory)

def gaussian(x, mu, sigma, depth):
    return depth * np.exp(-0.5 * ((x - mu) / sigma)**2)

def generate_spectra():
    # Define wavelength grid (LWIR)
    # 7.0 to 13.0 um covers most thermal features
    wavelengths = np.arange(7.0, 13.01, 0.05)
    
    # Define materials
    materials = {}
    
    # 1. MINERALS
    
    # Quartz: Distinct doublet features usually, here simplified as strong absorption
    # Dip around 8.3 and 9.1? Let's do a broad complex shape.
    q_feat = gaussian(wavelengths, 8.3, 0.3, 0.25) + gaussian(wavelengths, 9.1, 0.4, 0.20)
    materials['quartz'] = 0.96 - q_feat

    # Kaolinite: Feature near 10.5
    k_feat = gaussian(wavelengths, 10.5, 0.5, 0.15)
    materials['kaolinite'] = 0.98 - k_feat
    
    # Feldspar (Albite-like): Wide feature around 9.5-10.0
    f_feat = gaussian(wavelengths, 9.8, 0.7, 0.18)
    materials['feldspar'] = 0.95 - f_feat
    
    # Calcite: Sharp feature at 11.4
    c_feat = gaussian(wavelengths, 11.4, 0.15, 0.25)
    materials['calcite'] = 0.99 - c_feat
    
    # 2. VEGETATION
    # Green Leaf: Very high emissivity, almost blackbody, slight biological features but mostly flat
    materials['vegetation_green_leaf'] = np.full_like(wavelengths, 0.98)
    
    # 3. URBAN / MAN-MADE
    # Concrete: Grey body, slightly lower emissivity
    materials['urban_concrete'] = np.full_like(wavelengths, 0.93)
    
    # Asphalt: Darker in visible, but in Thermal usually high emissivity but broadband. 
    # Often cited around 0.93-0.95, sometimes lower if fresh. Let's use 0.90 for contrast.
    materials['urban_asphalt'] = np.full_like(wavelengths, 0.90)

    # --- SAVE ---
    PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    LIB_DIR = os.path.join(PROJECT_ROOT, 'data', 'raw', 'spectral_libraries')
    
    print(f"Cleaning directory: {LIB_DIR}")
    clean_and_create_dir(LIB_DIR)
    
    # Also define README
    readme_path = os.path.join(LIB_DIR, "README.txt")
    with open(readme_path, 'w') as f:
        f.write("MOCK SPECTRAL LIBRARY GENERATED BY create_full_mock_library.py\n")
        f.write("Replace these with real ECOSTRESS library files when available.\n")

    print("Generating spectra files...")
    for name, emissivities in materials.items():
        # Add a little generic noise to make it realistic? 
        # Ideally ground truth should be smooth, noise comes from sensor.
        # But let's keep it clean for ground truth.
        
        # Clip to [0, 1] just in case
        emissivities = np.clip(emissivities, 0.0, 1.0)
        
        filename = os.path.join(LIB_DIR, f"{name}.txt")
        with open(filename, 'w') as f:
            for w, e in zip(wavelengths, emissivities):
                f.write(f"{w:.2f} {e:.4f}\n")
    
    print(f"Successfully created {len(materials)} synthetic spectral files.")

if __name__ == "__main__":
    generate_spectra()
