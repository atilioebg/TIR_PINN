# MODTRAN Configuration - HARDCODED PATHS as per project decision
MODTRAN_DIR = r"C:\PcModWin5\bin"
MODTRAN_EXE_NAME = "Mod5.2.0.0.exe"

def write_tape5(
    filename: str, 
    model_atm: int = 2,     # 2 = Mid-Latitude Summer
    water_vapor: float = 1.0, # Scaling factor
    view_angle: float = 180.0,# 180 = Nadir looking down assuming sensor is above
    albedo: float = 0.3       # Soil albedo
) -> bool:
    """
    Writes a MODTRAN tape5 input file based on a simplified DISORT template.
    
    Args:
        filename (str): Output path for the tape5 file.
        model_atm (int): Atmospheric model selection (1-6).
        water_vapor (float): Water vapor scaling.
        view_angle (float): Sensor Zenith Angle.
        albedo (float): Surface albedo.
        
    Returns:
        bool: True if successful.
    """
    
    # NOTE: This is a MOCK template for a tape5 file. 
    # A real 'tape5' requires precise Fortran formatting (fixed column widths).
    # Since we cannot replicate the exact 100+ line structure here without specs,
    # we create a file that represents the CONFIGURATION intended.
    
    # In a real deployment, you would replace this string with a formatted 
    # f-string matching the MODTRAN5/6 User Guide.
    
    # Using a fake simplified format for demonstration of the control logic.
    content = f"""$MODTRAN INPUT FILE GENERATED BY ANTIGRAVITY
$MODEL_ATM : {model_atm}
$WATER_VAPOR : {water_vapor}
$VIEW_ANGLE : {view_angle}
$ALBEDO : {albedo}
$METHOD : DISORT (8 streams)
$RANGE : 7.0 - 13.0 microns
$END
"""
    # Writing the file
    with open(filename, 'w') as f:
        f.write(content)
    
    return True

