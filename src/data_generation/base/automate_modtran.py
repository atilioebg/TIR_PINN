def run_modtran_automation(
    output_dir: str,
    atm_models: List[int] = [2, 3],        # 2=MidLatSummer, 3=MidLatWinter
    water_vapor_scales: List[float] = [0.5, 1.0, 2.0],
    view_angles: List[float] = [180.0]       # 180 = Nadir
) -> None:
    """
    Automates MODTRAN runs for various conditions.
    Executes MODTRAN from its native directory to ensure DATA files are found.
    
    Args:
        output_dir (str): Directory to store results.
        atm_models (List[int]): List of atmospheric model IDs.
        water_vapor_scales (List[float]): Scaling factors for H2O.
        view_angles (List[float]): List of angles.
    """
    # 0. Setup directories
    original_cwd = os.getcwd()
    # Convert output_dir to absolute path because we will change CWD
    output_dir = os.path.abspath(output_dir)
    os.makedirs(output_dir, exist_ok=True)
    
    combinations = list(product(atm_models, water_vapor_scales, view_angles))
    print(f"Starting MODTRAN automation. Total scenarios: {len(combinations)}")
    
    results_summary = []
    
    try:
        # CRITICAL: Switch to MODTRAN directory so it can find its DATA folder
        print(f"Changing working directory to MODTRAN installation: {MODTRAN_DIR}")
        os.chdir(MODTRAN_DIR)
        
        # Verify executable exists in current directory (which is now MODTRAN_DIR)
        if not os.path.exists(MODTRAN_EXE_NAME):
            raise FileNotFoundError(f"MODTRAN executable '{MODTRAN_EXE_NAME}' not found in '{MODTRAN_DIR}'.")

        for i, (atm, h2o, angle) in enumerate(combinations):
            run_id = f"run_{i:04d}_atm{atm}_h2o{h2o}_ang{angle}"
            
            # 1. Generate TAPE5
            # We write 'tape5' directly in the current MODTRAN dir
            write_tape5("tape5", model_atm=atm, water_vapor=h2o, view_angle=angle)
            
            # 2. Execute MODTRAN
            try:
                # Run the executable blindly in the current dir
                # We expect it to read 'tape5' and produce 'tape7.scn' (or similar) in this dir
                # subprocess.DEVNULL suppresses the console popups/text if possible
                subprocess.run([MODTRAN_EXE_NAME], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                
                # 3. Handle Output
                # The output filename produced by MODTRAN is typically fixed (e.g. tape7.scn)
                default_out = "tape7.scn"
                
                if os.path.exists(default_out):
                    target_out = os.path.join(output_dir, f"{run_id}_tape7.txt")
                    shutil.copy(default_out, target_out)
                    
                    results_summary.append({
                        'run_id': run_id,
                        'atm_model': atm,
                        'water_vapor': h2o,
                        'view_angle': angle,
                        'output_file': target_out
                    })
                    
                    # Optional: Clean up tape7.scn to be ready for next run? 
                    # MODTRAN overwrites usually, but good practice.
                    # os.remove(default_out) 
                else:
                    print(f"Warning: {default_out} not generated for {run_id}")
                    
            except subprocess.CalledProcessError as e:
                print(f"MODTRAN Execution failed for {run_id}: {e}")
            except Exception as e:
                print(f"Run {run_id} failed: {e}")
                
    finally:
        # ALWAYS return to original directory to avoid side effects
        os.chdir(original_cwd)
        print("Returned to original working directory.")

    # Save Catalog
    if results_summary:
        df = pd.DataFrame(results_summary)
        catalog_path = os.path.join(output_dir, 'lut_catalog.csv')
        df.to_csv(catalog_path, index=False)
        print(f"Automation Complete. Catalog saved to {catalog_path}")
    else:
        print("No results were generated.")

if __name__ == "__main__":
    SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
    # Define project root relative to this script
    PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(SCRIPT_DIR))))
    
    # We no longer pass the executable path as it's hardcoded to the installation dir
    # to avoid 'DATA directory not found' errors.
    
    OUTPUT_DIR = os.path.join(PROJECT_ROOT, 'data', 'processed', 'atmospheric_luts')
    
    print(f"Target Output Directory: {OUTPUT_DIR}")
    run_modtran_automation(output_dir=OUTPUT_DIR)
